                <p style="margin-top:15px;">Next, the liquid refrigerant enters the evaporator, where it absorbs heat from the surroundings. This causes the evaporation of the refrigerant. This evaporation process extracts heat, resulting in a cooling effect. Finally, the refrigerant vapour is directed to the absorber, where it is absorbed by the absorbent, completing the cycle.


